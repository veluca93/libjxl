for _mod_name in ("optimizer", "compositing"):
  try:
    _mod = importlib.import_module(f"jxl_wasserstein.{_mod_name}")
    _pub = getattr(
        _mod,
        "__all__",
        [k for k in dir(_mod) if not k.startswith("_")],
    )
    for _sym in _pub:
      globals()[_sym] = getattr(_mod, _sym)
      if _sym not in __all__:
        __all__.append(_sym)
  except ImportError:
    pass


def __getattr__(name: str) -> Any:
  for mod_name in ("optimizer", "compositing"):
    try:
      mod = importlib.import_module(f"jxl_wasserstein.{mod_name}")
      if hasattr(mod, name):
        val = getattr(mod, name)
        globals()[name] = val
        if name not in __all__:
          __all__.append(name)
        return val
    except ImportError:
      continue
  raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
